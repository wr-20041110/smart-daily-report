def build_system_design() -> str:
    r = Report(str(OUT / "05-系统设计报告.docx"), "系统设计报告")
    r.h1("第1章 设计概述")
    r.p("本报告给出 v2（Superpowers 阶段）实现的设计说明：交互原型、工程目录、任务分解、测试用例与"
        "规范符合性。v1 设计见系统分析报告与 design.md 正文；v2 按“注册表 + 规则管道”架构从零重写"
        "（design.md 附录 A），两版功能等价、实现互不复制。")

    r.h1("第2章 界面原型与交互说明")
    r.h2("2.1 CLI 交互原型")
    r.p("运行：python -m daily_report_v2 --date 2026-12-01 --mock（--no-push 跳过推送）。输出原型：")
    r.p("智能日报生成器 v2.0.0｜日报日期：2026-12-01｜运行模式：Mock（内置模拟数据）｜"
        "采集结果：mock=56｜生成条目：9 条｜推送[email]：mock 留痕｜推送[feishu]：mock 留痕｜耗时：0.018s",
        indent=False)
    r.h2("2.2 团队日报样式原型（邮件与飞书共用 Markdown）")
    r.p("格式：# 团队日报 · 日期 → 数据来源/缺失数据源/Mock 标注行 → 每名成员 ## 小节 → "
        "### 开发/协作/讨论 三类条目 → 无记录成员标“今日无记录”。协作条目形如"
        "“09:25 新增飞书任务采集器重试逻辑（链接）｜你发起，协作：咸哲”；考勤行形如"
        "“考勤｜09:02 上午上班、18:05 下午下班”并置于开发分类顶部。", indent=False)
    r.h2("2.3 交互原则")
    r.bullet("数据诚实：mock 模式、缺失源、无记录成员三处显式标注；")
    r.bullet("可追溯：每条条目带原始事件链接与 raw_refs；")
    r.bullet("零手工：启动与配置之外无人工介入点（G4）。")

    r.h1("第3章 工程目录结构与部署设计")
    r.p("目录结构（README.md 有完整说明）：specs/ 三份规范与 UML 附件；src/daily_report_v1/ 与 "
        "src/daily_report_v2/ 两套实现；tests/v1/、tests/v2/ 测试；docs/reports/ 六份 Word 报告；"
        "docs/records/ 过程留痕；tools/ 报告生成与规范守护脚本；config.json 成员配置（入库）；"
        ".env 凭证（不入库）。", indent=False)
    r.p("部署：本地运行无需服务器——pip/uv 安装依赖 → 配置 config.json 与 .env → 一键 CLI。"
        "团队共用：Git 仓库分发（v1-sdd / v2-superpowers 两个 tag）；CI 门禁建议三处检查点："
        "① 提交前本地 pytest+ruff；② 合并前 code-review 工作流；③ 打 tag 前全量回归+覆盖率阈值。")

    r.h1("第4章 任务分解")
    r.p("任务清单见 specs/tasks-v2.md：初始 11 项（T201–T211）+ 变更单 3 项（T212–T214），"
        "每条任务含编号/交付物/验收标准/依赖/预估；一次提交对应一个任务（提交历史可查）。")
    r.fig("任务依赖图", "tasks-v2.md 第 3 节（T201→T202→T203 与并行组 {T204,T205,T206}）")
    r.table("任务分解摘要", T("任务", "交付物", "验收要点"),
            [T("T201-T202", "骨架/领域模型/配置", "CLI 可执行；frozen 数据类；纯函数构建"),
             T("T203", "存储层", "幂等建表/去重/按日期查询"),
             T("T204-T206", "三采集器（可并行）", "契约一致 + 全新 mock 数据集"),
             T("T207-T208", "规则引擎/编排", "RULES 管道；SC4 正确率 ≥95%"),
             T("T209-T210", "推送/管道/CLI", "mock 留痕/脱敏；降级出报"),
             T("T211", "回归与门禁", "SC 逐条核对；覆盖率 ≥85%"),
             T("T212-T214", "变更单考勤", "规范同步→采集器→全量回归")])

    r.h1("第5章 测试用例设计与执行结果")
    r.table("执行结果汇总", T("指标", "v1-SDD", "v2-Superpowers"),
            [T("测试用例数", "46", "56"),
             T("通过率", "46/46 = 100%", "56/56 = 100%"),
             T("归属正确率 SC4", "12/12", "12/12"),
             T("总覆盖率 / 核心模块", "92% / 生成层 94%", "93% / 规则 100%、编排 91%"),
             T("ruff 静态扫描", "0 告警", "0 告警"),
             T("mock 全流程耗时", "0.094s", "0.018s（含考勤 56 事件）")])
    r.p("代表性用例设计思路（从验收标准导出）：SC4 → 标注数据集比对测试（test_attribution_accuracy / "
        "test_sc4_attribution_accuracy_on_v2_dataset）；SC11 → 注入 2 次网络失败后成功的重试用例；"
        "SC2 → FailingCollector 故障注入降级用例；F12 → 考勤行置顶与数量断言。")

    r.h1("第6章 规范符合性说明")
    r.table("与 specs/ 一致性自查", T("检查项", "结果"),
            [T("proposal 范围 F1–F12 全部实现", "✅（F12 为变更单新增，两版对照见验收核对记录）"),
             T("design 接口契约逐条落地", "✅（红队评审 8 条意见全部回应，见 04-红队评审单）"),
             T("tasks 任务与提交历史对应", "✅（一次提交一个任务，v2 message 含任务编号）"),
             T("UML 附件与实现一致", "✅（规范审计报告第 2 节）"),
             T("代码与规范冲突处理", "✅（变更涟漪演练：先规范后代码，缺陷 D1/D2 记录在案）")])
    r.p("结论：系统设计与 specs/ 规范保持一致，无未修复偏差；规范守护脚本（tools/spec_guard.py）"
        "用于“改了代码未改规范”的持续检查。")
    return r.save()


