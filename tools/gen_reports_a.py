from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from reportkit import Report, T  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "docs" / "reports"


# --------------------------------------------------------------------------
# 01 业务调研报告
# --------------------------------------------------------------------------


def build_business_survey() -> str:
    r = Report(str(OUT / "01-业务调研报告.docx"), "业务调研报告")
    r.h1("第1章 调研大纲")
    r.h2("1.1 调研目标")
    r.p("本次调研为“智能日报生成器”项目确定功能范围、交互形态与成功标准，回答三个问题：")
    r.bullet("同类日报/周报自动化方案有哪些形态？各自的核心流程与数据源是什么？")
    r.bullet("目标用户（团队成员与组长）的真实痛点是否与我们的五痛点假设一致？")
    r.bullet("哪些能力是市面方案的空白，可以成为本项目的差异化定位？")
    r.h2("1.2 调研对象")
    r.p("选取三类具有代表性的方案：A 项目管理工具自带日报/周报功能（TAPD 周报、Jira 工作日志）；"
        "B 开源日报机器人（GitHub 上 daily-report / 周报 bot 类项目）；"
        "C 低代码方案（飞书多维表格 + 自动化工作流）。覆盖“平台内置 / 开源自部署 / 低代码”三种形态。")
    r.h2("1.3 行业定位")
    r.p("智能日报属于“研发效能（Engineering Productivity）”工具域：以可观测的工作痕迹（提交、任务、消息）"
        "自动生成面向人阅读的日报。行业趋势是数据源从单平台走向多平台聚合、从人工填报走向自动采集。")

    r.h1("第2章 调研目标分析")
    r.h2("2.1 解决的用户问题")
    r.p("对照指导书第一部分列出的五个痛点（靠回忆、多平台复制粘贴、遗漏、协作成果没人记、格式不一），"
        "三个调研对象均只能部分解决：")
    r.table("调研对象与五痛点覆盖对照", T("痛点", "A 平台内置", "B 开源 bot", "C 低代码"),
            [T("① 靠回忆", "部分（平台内工作项）", "解决（提交自动采集）", "不解决（表格人工维护）"),
             T("② 多平台复制粘贴", "不解决（单平台）", "不解决（多为单数据源）", "部分（飞书内）"),
             T("③ 遗漏", "部分", "解决", "不解决"),
             T("④ 协作成果没人记", "不解决", "不解决", "不解决"),
             T("⑤ 格式不一、手工汇总", "解决（模板导出）", "解决（模板渲染）", "解决（卡片模板）")])
    r.p("结论：协作成果自动归属是三个调研对象的共同空白，也是本项目核心差异化（见第 4 章结论 1）。")
    r.h2("2.2 采用的架构与流程")
    r.p("调研对象普遍采用“采集 → 聚合 → 模板渲染 → 推送”的四段流程。本项目继承该流程骨架，"
        "按课程要求构建为“采集层 → 生成层 → 推送层 → 主编排入口”四层架构，并新增协同归属环节（design.md 第 1 章）。")
    r.h2("2.3 带来的好处")
    r.bullet("对成员：日报从真实工作数据自动长出来，零手工编写；")
    r.bullet("对组长：格式统一、一键汇总、协作成果不再漏记；")
    r.bullet("对团队：日报历史可追溯（每条条目带原始事件引用），形成可审计的工作记录。")

    r.h1("第3章 调研内容分析")
    r.h2("3.1 受众用户")
    r.p("直接用户：团队成员（核对本人条目、补写遗漏）；组长（审阅全组日报、接收推送）。"
        "间接用户：指导教师与企业导师（阶段评审与答辩演示）。")
    r.h2("3.2 核心功能模块")
    r.table("调研对象功能模块对比", T("功能模块", "A 平台内置", "B 开源 bot", "C 低代码", "本项目"),
            [T("数据采集", "工作项流水", "GitHub 提交", "表格读取", "GitHub+飞书三源"),
             T("成员聚合", "按人聚合周报", "按作者聚合", "无", "按人+按分类聚合"),
             T("协作归属", "手动关联", "无", "无", "自动（R1/R2/R3）"),
             T("模板渲染", "内置模板", "YAML 配置模板", "卡片模板", "Markdown 统一模板"),
             T("推送", "邮件订阅", "webhook", "群消息", "邮件+飞书机器人"),
             T("历史留存", "平台内置", "无", "表格本身", "SQLite 三表")])
    r.h2("3.3 UI 风格")
    r.p("A 以 Web 界面为主（工作台+报表页）；B 无界面（配置驱动+消息推送）；C 在飞书客户端内配置。"
        "本项目 v1 采用“CLI + 推送交付”的 B 型风格，Web 界面明确列入不做什么（proposal X2），"
        "把精力集中到自动化与归属正确性上。")
    r.h2("3.4 核心流程")
    r.p("调研对象共同的核心流程为：数据源记录工作痕迹 → 定时/手动触发 → 按人聚合 → 模板渲染 → 推送。"
        "本项目对应流程见需求分析报告第 2 章泳道图（specs/uml/swimlane.puml），"
        "与调研对象的关键差异在“聚合”与“渲染”之间插入协同归属环节。")
    r.fig(
        "开源日报机器人调研截图（方案 B）",
        "perrycan/wechat-daily-report-bot 项目 README 截图，归档于 docs/records/调研截图/",
        png=str(OUT.parent / "records" / "调研截图" / "b-开源bot-微信接龙日报.png"),
    )
    r.fig(
        "飞书多维表格调研截图（方案 C）",
        "飞书客户端工作台实测截图，归档于 docs/records/调研截图/",
        png=str(OUT.parent / "records" / "调研截图" / "c-飞书多维表格.png"),
    )
    r.fig(
        "Teambition 周报管理调研截图（方案 A）",
        "Teambition 客户端实测截图，归档于 docs/records/调研截图/",
        png=str(OUT.parent / "records" / "调研截图" / "a-teambition周报管理.png"),
    )

    r.h1("第4章 调研结论分析")
    r.h2("4.1 易用性对比")
    r.table("易用性对比（1–5 分，5 为最优）", T("维度", "A 平台内置", "B 开源 bot", "C 低代码"),
            [T("部署成本", "2", "3", "4"),
             T("数据完整度", "3", "2", "2"),
             T("自动化程度", "3", "4", "3"),
             T("协作归属", "1", "1", "1"),
             T("可定制性", "2", "4", "3")])
    r.h2("4.2 优缺点与差异化结论")
    r.bullet("A 优点：与项目数据同源；缺点：单平台、粒度偏周报、归属靠手动。")
    r.bullet("B 优点：轻量、真正“自动长出来”；缺点：数据源单一、无归属、历史留存弱。")
    r.bullet("C 优点：零代码；缺点：表格需人工维护、跨平台接入弱、复杂逻辑受限。")
    r.p("结论：本项目定位为“三源自动采集 + 协同自动归属 + 零手工”的组合体——取 A 的按人聚合与模板统一、"
        "B 的自动化理念与轻量交付，补上三者共同的协作归属空白。该结论已写入 proposal.md 背景与范围。")

    r.h1("第5章 技术调研分析")
    r.table("同类系统技术栈对比", T("方案", "语言/框架", "存储", "推送通道", "采集方式"),
            [T("TAPD/Jira 类", "平台闭源", "平台数据库", "邮件/站内信", "平台内埋点"),
             T("开源日报 bot", "Python/Node", "无或 JSON", "webhook（Slack/飞书/企微）", "GitHub API"),
             T("飞书低代码", "无代码", "多维表格", "群消息卡片", "表格读取/日历")])
    r.p("本项目技术栈（Python 3.12+ / httpx / SQLite / SMTP+飞书机器人）的逐项论证见技术调研报告第 2–4 章，"
        "结论与 design.md 中 ADR-001～004 一一对应。")

    r.h1("第6章 结论")
    r.p("调研结论四条：① 协作自动归属是市面空白，为本项目差异化；② UI 取 CLI+推送形态，Web 明确不做；"
        "③ 流程骨架继承“采集→聚合→渲染→推送”并插入归属环节；④ 成功标准聚焦可度量指标"
        "（归属正确率 ≥95%、全流程 ≤10s、覆盖率 ≥85%，见 proposal.md 第 5 章）。")
    r.p("三源核验说明：本报告全部外部产品结论均有两个独立来源互证（来源清单见 docs/records/03-竞品调研记录.md"
        "“三源核验记录”表）；截图证据需组员按实际调研补充后替换占位。")
    return r.save()


