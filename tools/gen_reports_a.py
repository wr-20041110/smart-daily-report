def build_requirements() -> str:
    r = Report(str(OUT / "02-需求分析报告.docx"), "需求分析报告")
    r.h1("第1章 概述")
    r.h2("1.1 总体目标")
    r.p("让日报从成员的真实工作数据中自动长出来：采集 GitHub 提交、飞书任务流转与群消息三源数据"
        "（v1.1 起含飞书考勤），自动生成个人日报条目并完成协同成果归属，编排为格式统一的团队日报，"
        "经邮件与飞书机器人推送，SQLite 留存历史。人工介入点仅剩启动流程与一次性配置成员清单。")
    r.h2("1.2 具体目标（均可度量）")
    r.table("可度量目标", T("编号", "目标", "度量"),
            [T("G1", "一键跑通，全流程 ≤10s（mock ≤200 事件）", "计时"),
             T("G2", "覆盖全员，条目含开发/协作/讨论三类", "日报文本断言"),
             T("G3", "协同归属正确率 ≥95%（12 条标注事件）", "测试比对标注答案"),
             T("G4", "自动化率 100%（人工仅剩启动与配置）", "流程检查"),
             T("G5", "日报历史可按日期查询", "SQL 查询"),
             T("G6", "任一数据源失败降级出报", "故障注入测试"),
             T("G7", "生成核心逻辑语句覆盖率 ≥85%", "coverage 报告")])

    r.h1("第2章 业务流程")
    r.p("核心业务流程为：团队成员当日工作（提交代码、流转任务、群内讨论）→ 外部平台留存痕迹 → "
        "采集层三源拉取并归一化为 RawEvent → 生成层按协同归属规则聚合为个人条目 → 编排团队日报 → "
        "SQLite 落库 → 邮件与飞书推送 → 组长接收审阅。")
    r.fig("业务流程图（泳道图）", "PlantUML 工具绘制，源文件 specs/uml/swimlane.puml",
          png=str(OUT / "figures" / "swimlane.png"))
    r.p("异常流程：任一数据源失败 → 重试 3 次指数退避 → 仍失败则记入缺失源并降级出报，"
        "日报头部显式标注“无数据”；凭证缺失 → 全流程自动进入 mock 模式并显式标注。")

    r.h1("第3章 功能需求")
    r.h2("3.1 涉众分析")
    r.table("涉众分析", T("涉众", "角色", "主要关注点"),
            [T("团队成员", "数据生产者/日报读者", "条目准确、协作成果被记上"),
             T("组长", "日报审阅者", "格式统一、缺漏可见"),
             T("配置管理员", "系统运维者", "凭证安全、可追溯"),
             T("教师/企业导师", "评审者", "规范可验证、演示可运行")])
    r.h2("3.2 用例图与用例模板")
    r.fig("用例图", "PlantUML 工具绘制，源文件 specs/uml/usecase.puml",
          png=str(OUT / "figures" / "usecase.png"))
    r.h3("用例模板（节选 UC1/UC5/UC12）")
    r.table("UC1 采集 GitHub 提交", T("项", "内容"),
            [T("参与者", "定时/手动触发（主编排）"), T("前置", "GITHUB_TOKEN 已注入；仓库地址已配置"),
             T("主流程", "1 换算当日 UTC 区间 2 分页拉取 commits 3 过滤团队成员 4 解析 Co-authored-by 5 归一化为 RawEvent"),
             T("后置", "返回当日提交事件列表；请求数 ≤20"), T("异常", "限流/网络失败：重试 3 次后退避；凭证缺失：抛凭证异常")])
    r.table("UC5 协同成果自动归属", T("项", "内容"),
            [T("参与者", "生成层"), T("前置", "采集层已产出 RawEvent"),
             T("主流程", "按 R1 共同提交 / R2 协作任务 / R3 群内@关联任务 三条规则匹配，命中者为发起人+协作者生成协作条目"),
             T("后置", "12 条标注事件归属正确率 ≥95%"), T("异常", "账号无法映射：归入“未映射”条目，不丢弃")])
    r.table("UC12 一键运行日报流程", T("项", "内容"),
            [T("参与者", "配置管理员/组长"), T("前置", "config.json 成员清单已配置"),
             T("主流程", "CLI 启动 → 采集 → 生成 → 存储 → 推送 → 输出 PipelineResult 汇总"),
             T("后置", "退出码 0；日报留存 SQLite；推送留痕"), T("异常", "生成/存储失败退出码 1 且不推送；数据源失败降级出报")])
    r.h2("3.3 功能需求清单")
    r.p("功能条目 F1–F12 逐条编号于 proposal.md 第 3.1 节（F12 为 v1.1 变更单新增考勤采集）；"
        "需求→用例→类→表的逐级追溯对照如下：")
    r.table("可追溯对照表（节选）", T("proposal 条目", "用例", "类/模块", "表"),
            [T("F1 GitHub 提交采集", "UC1", "GitHubCollector / fetch_github", "raw_events"),
             T("F4 个人日报生成", "UC4", "ReportGenerator / build_entries", "daily_reports"),
             T("F5 协同归属", "UC5", "协同归属规则 R1–R3", "daily_reports.raw_refs"),
             T("F6 团队日报编排", "UC6", "build_team_report / render_team_report", "team_reports"),
             T("F12 考勤采集（v1.1）", "UC1（扩展）", "fetch_feishu_attendance", "raw_events")])

    r.h1("第4章 非功能性需求")
    r.table("非功能性需求", T("类别", "需求", "验收"),
            [T("性能", "mock 全流程 ≤10s；单源单轮请求 ≤20", "SC7/SC8"),
             T("安全", "凭证仅环境变量注入；日志脱敏；SQL 参数化", "ADR-003 + 安全自检"),
             T("可靠性", "重试 3 次指数退避后降级出报；重跑幂等", "SC11 + 幂等测试"),
             T("运行环境", "Python 3.12+；Windows/macOS/Linux；SQLite 零部署", "环境清单（指导书第三部分）"),
             T("可维护性", "数据源可替换（同契约新增采集源）", "v2 注册表机制"),
             T("将来可能的需求", "AI 智能摘要、Web 界面、多团队多租户、考勤（v1.1 已实施）", "proposal“不做什么”X1/X2/X4 及变更记录")])

    r.h1("第5章 数据需求")
    r.h2("5.1 数据实体")
    r.p("核心实体四个：Member（成员，平台账号映射）、RawEvent（原始事件，采集层统一格式）、"
        "DailyReportEntry（个人日报条目）、TeamReport（团队日报）；字段与约束见 design.md 3.1。")
    r.h2("5.2 数据流转")
    r.p("外部平台 →（采集归一化）→ RawEvent →（归属与聚合）→ DailyReportEntry →（编排）→ TeamReport "
        "→（落库）→ SQLite 三表（raw_events / daily_reports / team_reports，ER 图见系统分析报告第 4 章）"
        "→（渲染）→ Markdown 全文 →（推送）→ 邮件/飞书。事件 UTC 存储、本地（Asia/Shanghai）展示。")
    r.h2("5.3 数据规模")
    r.p("单团队单日约 200 条原始事件、12 条个人条目、1 份团队日报，远小于 SQLite 容量上限（ADR-002）。")

    r.h1("第6章 验收标准")
    r.p("验收标准 SC1–SC12（功能/性能/边界三类）逐条定义于 proposal.md 第 5 章，"
        "v1 与 v2 两套实现的逐条核对结果见 docs/records/13-验收核对记录.md（两版全部通过，"
        "SC4 归属正确率两版均为 12/12）。")
    r.table("验收标准概要", T("类别", "标准", "数量"),
            [T("功能验收", "SC1–SC6（一键可跑/独立降级/全员覆盖/归属正确率/历史可查/推送留痕）", "6 条"),
             T("性能验收", "SC7–SC8（≤10s/请求上限）", "2 条"),
             T("边界场景", "SC9–SC12（无记录成员/凭证缺失/异常降级/时区边界）", "4 条")])
    return r.save()


if __name__ == "__main__":
    print(build_business_survey())
